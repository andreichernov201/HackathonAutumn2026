import { expect, test } from '@playwright/test'

test('original PDF pages, zoom, full-document search and return to cited text', async ({ page }, testInfo) => {
  const workerResponse = page.waitForResponse((response) => /pdf\.worker.*\.mjs$/.test(response.url()))
  await page.goto('/#knowledge')
  expect((await workerResponse).headers()['content-type']).toMatch(/javascript/)
  const viewer = page.getByRole('region', { name: 'Просмотр PDF' })
  await expect(viewer.getByRole('button', { name: 'Следующая страница PDF' })).toBeEnabled({ timeout: 30000 })
  await expect(viewer.locator('canvas').first()).toBeVisible()
  await expect(viewer.getByRole('spinbutton', { name: 'Номер страницы PDF' })).toHaveAttribute('max', '51')
  await viewer.getByRole('button', { name: 'Следующая страница PDF' }).click()
  await expect(viewer.getByRole('spinbutton', { name: 'Номер страницы PDF' })).toHaveValue('2')
  const zoom = viewer.getByLabel('Масштаб PDF')
  const before = await zoom.innerText()
  await viewer.getByRole('button', { name: 'Увеличить PDF' }).click()
  await expect(zoom).not.toHaveText(before)
  await viewer.getByRole('button', { name: 'Поиск по документу', exact: true }).click()
  await viewer.getByRole('textbox', { name: 'Поиск в PDF' }).fill('регистрационный')
  await viewer.getByRole('button', { name: 'Найти', exact: true }).click()
  await expect(viewer.getByRole('button', { name: 'Следующее совпадение PDF' })).toBeEnabled({ timeout: 30000 })
  await expect(viewer.locator('.textLayer .highlight.selected').first()).toBeVisible()
  await viewer.getByRole('button', { name: 'Следующее совпадение PDF' }).click()
  await expect(viewer.locator('.dv-search [role="status"]')).toContainText('из')
  await expect(viewer.locator('.textLayer .highlight.selected').first()).toBeVisible()
  const top = await viewer.locator('.dv-scroll').evaluate((node) => {
    node.scrollTop += 150
    return node.scrollTop
  })
  await expect.poll(() => viewer.locator('.dv-scroll').evaluate((node) => node.scrollTop)).toBe(top)
  await viewer.getByRole('button', { name: 'Развернуть PDF', exact: true }).click()
  await expect(page.locator('.document-viewer:fullscreen')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('pdf-viewer.png') })
  await viewer.getByRole('button', { name: 'Свернуть PDF', exact: true }).click()
  await expect(page.locator('.document-viewer:fullscreen')).toHaveCount(0)
  await page.getByRole('tab', { name: 'Содержание', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Содержание документа' })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Спросить ИИ:/ }).first()).toBeVisible()
})
